  give(t: ServerPlayer, id: string, count: number, opts: { potion?: string; enchant?: string; level?: number } = {}): { ok: boolean; text: string } {
    const it = itemById.get(id);
    if (!it || it.num === 0 || id === 'air') return { ok: false, text: `Unknown item ${id}.` };
    const proto: ItemStack = { id: it.num, count: 1 };
    if (opts.potion) {
      if (!POTION_BY_ID.has(opts.potion) || (it.id !== 'potion' && it.id !== 'splash_potion')) return { ok: false, text: 'That potion type does not exist.' };
      proto.tag = { potion: opts.potion };
    }
    if (opts.enchant) {
      if (!ENCHANT_BY_ID.has(opts.enchant)) return { ok: false, text: 'Unknown enchantment.' };
      const lvl = Math.max(1, Math.min(10, opts.level ?? 1));
      proto.tag = { ...(proto.tag ?? {}), ...(it.id === 'enchanted_book' ? { stored: { [opts.enchant]: lvl } } : { ench: { [opts.enchant]: lvl } }) };
    }
    markAdmin(proto);
    // Unstackable items: at most a full inventory; the rest would only litter the ground
    const max = it.maxStack === 1 ? 36 : 64 * 36;
    const total = Math.min(count, max);
    let left = total;
    let dropped = 0;
    while (left > 0) {
      const n = Math.min(left, it.maxStack);
      const st: ItemStack = { ...proto, count: n, ...(proto.tag ? { tag: JSON.parse(JSON.stringify(proto.tag)) } : {}) };
      const rem = t.inventory.add(st);
      if (rem) {
        if (dropped < 64) this.server.interaction.dropStack(t, rem);
        dropped++;
      }
      left -= n;
    }
    this.server.interaction.syncInventory(t);
    const nm = it.def.name + (opts.potion ? ` (${POTION_BY_ID.get(opts.potion)!.name})` : '') + (opts.enchant ? ` (${ENCHANT_BY_ID.get(opts.enchant)!.name} ${opts.level ?? 1})` : '');
    return { ok: true, text: `Gave ${total} ${nm} to ${t.name}${total < count ? ` (limited to ${total})` : ''}${dropped ? '; some were dropped at their feet' : ''}.` };
  }

  spawn(p: ServerPlayer, type: string, count: number): { ok: boolean; text: string } {
    const s = this.server;
    const def = mobDef(type);
    if (!def || !s.mobs) return { ok: false, text: `Unknown mob ${type}.` };
    if (type === 'ender_dragon') {
      // In the End the dragon joins the real fight (with its arena rules)
      if (p.dim.id === 'end' && s.theEnd) {
        if (s.theEnd.fight.dragon) return { ok: false, text: 'An Ender Dragon is already alive here.' };
        const m = s.theEnd.fight.spawnDragon();
        if (!m) return { ok: false, text: 'Could not spawn the dragon.' };
        m.admin = true;
        return { ok: true, text: 'Spawned an Ender Dragon (admin: its defeat will not count for advancements).' };
      }
      count = 1;
    }
    const dir = [-Math.sin(p.yaw), -Math.cos(p.yaw)];
    let n = 0;
    if (type === 'warden' && s.warden) {
      // Wardens climb out of the ground like a summoned one, marked as admin
      // (never counts for advancements); capped so the panel can't flood a world
      count = Math.min(count, 3);
      for (let i = 0; i < count; i++) {
        const w = s.warden.summon(p.dim, p.x + dir[0]! * 6, p.y, p.z + dir[1]! * 6, null, { admin: true });
        if (w) n++;
      }
      return { ok: n > 0, text: n > 0 ? `Summoned ${n} admin Warden${n === 1 ? '' : 's'} (it will not count for advancements).` : 'No room for a Warden to emerge here.' };
    }
    for (let i = 0; i < count; i++) {
      const d = 3 + Math.min(4, def.width) + Math.random() * 2;
      const x = p.x + dir[0]! * d + (Math.random() - 0.5) * 3;
      const z = p.z + dir[1]! * d + (Math.random() - 0.5) * 3;
      const y = this.standY(p.dim, x, p.y, z) ?? p.y;
      const m = s.mobs.spawn(p.dim, type, x, y, z, { reason: 'admin', persistent: true });
      if (!m) continue;
      m.admin = true;
      n++;
    }
    return { ok: n > 0, text: n > 0 ? `Spawned ${n} ${def.name}${n === 1 ? '' : 's'}.` : `Could not spawn ${def.name}.` };
  }

  /** A standing height near y at a column (loaded chunks only). */
  private standY(dim: Dimension, x: number, y: number, z: number): number | null {
    const bx = Math.floor(x);
    const bz = Math.floor(z);
    if (!dim.isLoaded(bx, bz)) return null;
    for (let dy = 0; dy < 12; dy++) {
      for (const yy of [Math.floor(y) + dy, Math.floor(y) - dy]) {
        if (yy < 1 || yy > 254) continue;
        if (STATE_SOLID[dim.getState(bx, yy - 1, bz)] && !STATE_SOLID[dim.getState(bx, yy, bz)] && !STATE_SOLID[dim.getState(bx, yy + 1, bz)]) return yy;
      }
    }
    return null;
  }

