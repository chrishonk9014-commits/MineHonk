/**
 * Admin Panel and cheat commands.
 *
 * Authorisation: every request is checked here, on the server, against the
 * sender's role (world owner or operator) and the world's cheats setting.
 *
 * Advancement safety: everything a cheat creates is marked (items get an
 * `admin` tag, mobs and other entities an `admin` flag, placed blocks a
 * position mark, XP an admin share), cheat teleports mark the place (or the
 * whole visit to another dimension) the player arrived in, and cheat game
 * modes and flight mark the player while they last. Advancements are only
 * granted outside that context (see Interaction.grant), and the marks carry
 * through crafting, smelting, brewing, trading, breeding and drops, so a chain
 * of events started by a cheat stays advancement-neutral. Normal play is
 * untouched.
 */
