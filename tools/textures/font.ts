export interface GlyphData {
  w: number;
  rows: string[];
}

export function glyphTable(): Record<string, GlyphData> {
  const out: Record<string, GlyphData> = {};
  for (const [ch, s] of Object.entries(GLYPHS)) {
    const rows = s.split('/');
    const w = Math.max(...rows.map((r) => r.length));
    while (rows.length < 9) rows.push('.'.repeat(w));
    out[ch] = { w, rows: rows.map((r) => r.padEnd(w, '.')) };
  }
  return out;
}
